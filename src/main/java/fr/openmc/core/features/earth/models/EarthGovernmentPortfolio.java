package fr.openmc.core.features.earth.models;

/**
 * Country portfolios intentionally describe responsibilities rather than a
 * particular constitutional model. Configured government types can expose the
 * same portfolios as ministers, secretaries, commissioners, or departments.
 */
public enum EarthGovernmentPortfolio {
    FINANCE,
    HEALTH,
    EDUCATION,
    INFRASTRUCTURE,
    ENVIRONMENT,
    PUBLIC_SAFETY,
    LABOUR,
    FOREIGN_AFFAIRS
}
